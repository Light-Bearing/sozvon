export const SCREENS = ['start', 'join', 'call', 'failed', 'diagnostics'];

export const showScreen = (root, name) => {
  if (!SCREENS.includes(name)) throw new Error(`Нет такого экрана: ${name}`);
  for (const screen of SCREENS) {
    const el = root.querySelector(`#screen-${screen}`);
    if (el) el.hidden = screen !== name;
  }
};

// Человеку на экране не нужны названия ошибок — нужно понять,
// что случилось и что делать дальше.
export const explainFailure = error => {
  switch (error?.name) {
    case 'NotAllowedError':
      return {
        title: 'Браузер не пустил к камере и микрофону',
        advice:
          'Нажмите на значок замка слева от адреса и разрешите камеру и микрофон, ' +
          'потом обновите страницу.',
      };
    case 'NotFoundError':
      return {
        title: 'Камера или микрофон не найдены',
        advice:
          'Проверьте, подключены ли они, и не занял ли их другой звонок или программа.',
      };
    case 'NotReadableError':
      return {
        title: 'Камеру занял кто-то другой',
        advice: 'Закройте другие программы, которые могут её использовать, и попробуйте снова.',
      };
    default:
      return {
        title: 'Связь не установилась',
        advice:
          'Загляните в проверку связи — там видно, что именно не работает: каналы, ' +
          'через которые вас находят, или сама сеть.',
      };
  }
};

// Что делает лестница качества, когда людей становится много. Сказать это
// вслух обязательно: иначе выключенные ею камеры выглядят как поломка —
// все плитки тёмные, и непонятно, кто виноват и что чинить.
export const explainStep = (step, people) => {
  if (!step || step.videoFor === 'all') return '';
  const сколько = people > 1 ? `Вас ${people}` : 'Людей много';
  return step.videoFor === 'speaker'
    ? `${сколько} — камера включается у того, кто говорит`
    : `${сколько} — идёт только звук, без камер`;
};

// Виды бед — в src/signal/trouble.js. Порядок здесь — по объяснительной
// силе: если не достучались до нескольких человек по разным причинам,
// показать надо ту, из которой понятно, что делать.
const BY_WEIGHT = ['no-path', 'wrong-key', 'handshake'];

const worstKind = kinds =>
  BY_WEIGHT.find(kind => kinds.includes(kind)) ?? kinds[0];

// Сколько человек осталось за бортом — по-русски, а не числом: «с одним»
// читается как предложение, «с 1» — как отчёт.
const СКОЛЬКО = ['', 'с одним участником', 'с двумя участниками', 'с тремя участниками'];

const howMany = count => СКОЛЬКО[count] ?? `с ${count} участниками`;

// Беда, о которой сообщили каналы связи. Это не отказ: звонок продолжает
// попытки, поэтому текст объясняет, что происходит, и что делать, — но не
// выгоняет человека с экрана звонка.
//
// Доводом идёт список, а не один вид, потому что в разговоре втроём и
// больше «связь не встала» без счёта неотличимо от «звонок не работает
// вовсе». Живой разговор на пятерых показал ровно это: двое не видели
// друг друга, остальные не видели в этом ничего особенного.
export const explainTrouble = (troubles, {relayReady = false} = {}) => {
  const list = Array.isArray(troubles) ? troubles : [{kind: troubles}];
  if (list.length === 0) return {title: '', advice: ''};

  const kind = worstKind(list.map(item => item?.kind ?? item));
  const count = new Set(list.map((item, i) => item?.peerId ?? i)).size;
  const {title, advice} = textFor(kind);

  return {
    // Когда не достучались до одного, человеку нужна причина. Когда до
    // нескольких — сперва счёт: он один говорит, что разговор идёт, но не
    // весь.
    title: count > 1 ? `Связь не встала ${howMany(count)}` : title,
    advice:
      advice +
      (count > 1 ? ' Остальных вы видите и слышите — разговор идёт без них.' : '') +
      (kind === 'no-path' && !relayReady
        ? ' Ретранслятор чинит ровно этот случай, и довольно, чтобы он был ' +
          'у одного — у того, кто рассылает ссылку.'
        : ''),
  };
};

const textFor = kind => {
  switch (kind) {
    // Совет про «раздайте интернет с телефона» отсюда убран намеренно: он
    // годится, только когда собеседники в одной комнате и меняют сеть на
    // соседнюю. Двоим в разных странах он не помогает ничем, а звучит как
    // решение — то есть врёт.
    case 'no-path':
      return {
        title: 'Прямого пути между вашими сетями нет',
        advice:
          'Вы нашли друг друга, а канал не сложился: чья-то сеть не выпускает ' +
          'звонок наружу. Помогает любая другая сеть — мобильный интернет вместо ' +
          'Wi-Fi или наоборот, у кого угодно из вас. «Проверить связь» на первом ' +
          'экране скажет, ваша ли сторона тому виной.',
      };
    case 'wrong-key':
      return {
        title: 'У собеседника другая ссылка',
        advice:
          'Пришлите ссылку заново и целиком — вместе с хвостом после решётки. ' +
          'Без него это уже другой разговор.',
      };
    case 'handshake':
      return {
        title: 'Соединение оборвалось на полуслове',
        advice: 'Попытки продолжаются. Обычно со второго раза встаёт.',
      };
    default:
      return {
        title: 'Соединиться с собеседником не вышло',
        advice:
          'Попытки продолжаются. Если так и не выйдет, загляните в проверку связи ' +
          'на первом экране.',
      };
  }
};
