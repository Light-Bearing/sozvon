export const SCREENS = ['start', 'join', 'call', 'failed', 'diagnostics'];

export const showScreen = (root, name) => {
  if (!SCREENS.includes(name)) throw new Error(`Нет такого экрана: ${name}`);
  for (const screen of SCREENS) {
    const el = root.querySelector(`#screen-${screen}`);
    if (el) el.hidden = screen !== name;
  }
};

// Человеку на экране не нужны названия ошибок — нужно понять,
// что случилось и что делать дальше.
export const explainFailure = error => {
  switch (error?.name) {
    case 'NotAllowedError':
      return {
        title: 'Браузер не пустил к камере и микрофону',
        advice:
          'Нажмите на значок замка слева от адреса и разрешите камеру и микрофон, ' +
          'потом обновите страницу.',
      };
    case 'NotFoundError':
      return {
        title: 'Камера или микрофон не найдены',
        advice:
          'Проверьте, подключены ли они, и не занял ли их другой звонок или программа.',
      };
    case 'NotReadableError':
      return {
        title: 'Камеру занял кто-то другой',
        advice: 'Закройте другие программы, которые могут её использовать, и попробуйте снова.',
      };
    default:
      return {
        title: 'Связь не установилась',
        advice:
          'Чаще всего помогает раздать интернет с телефона и попробовать снова. ' +
          'Если не поможет — загляните в диагностику, там видно, что именно не работает.',
      };
  }
};

// Беда, о которой сообщили каналы связи (виды — в src/signal/trouble.js).
// Это не отказ: звонок продолжает попытки, поэтому текст объясняет, что
// происходит, и что делать, — но не выгоняет человека с экрана звонка.
export const explainTrouble = kind => {
  switch (kind) {
    case 'no-path':
      return {
        title: 'Собеседник нашёлся, а канал к нему — нет',
        advice:
          'Ваши устройства увидели друг друга, но соединиться напрямую не смогли: ' +
          'сеть не пропускает звонок. Надёжнее всего помогает раздача интернета ' +
          'с телефона — у любого из вас.',
      };
    case 'wrong-key':
      return {
        title: 'У собеседника другая ссылка',
        advice:
          'Пришлите ссылку заново и целиком — вместе с хвостом после решётки. ' +
          'Без него это уже другой разговор.',
      };
    case 'handshake':
      return {
        title: 'Соединение оборвалось на полуслове',
        advice: 'Попытки продолжаются. Обычно со второго раза встаёт.',
      };
    default:
      return {
        title: 'Соединиться с собеседником не вышло',
        advice:
          'Попытки продолжаются. Если так и не выйдет, загляните в проверку связи ' +
          'на первом экране.',
      };
  }
};
