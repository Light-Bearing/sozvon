// Род — номер формы прилагательного: 0 мужской, 1 женский, 2 средний.
export const NOUNS = [
  ['Пингвин', 0], ['Ёж', 0], ['Бобр', 0], ['Кит', 0], ['Барсук', 0],
  ['Тюлень', 0], ['Чайник', 0], ['Компас', 0], ['Фонарь', 0], ['Кактус', 0],
  ['Выдра', 1], ['Сова', 1], ['Черепаха', 1], ['Лиса', 1], ['Ондатра', 1],
  ['Ракета', 1], ['Лампа', 1], ['Тумбочка', 1],
  ['Облако', 2], ['Полотенце', 2], ['Ведро', 2], ['Зеркало', 2], ['Эхо', 2],
];

export const MAX_NAME = 24;

const pick = (list, random) => list[Math.floor(random() * list.length)];

export const makeName = (random = Math.random) => {
  const [noun, gender] = pick(NOUNS, random);
  return `${pick(ADJECTIVES, random)[gender]} ${noun}`;
};

// Имя уходит собеседникам и рисуется на плитке, поэтому лишние пробелы и
// переводы строк схлопываем, а длину режем: чужая строка в свою разметку
// попадает только через textContent, но ширину плитки она всё равно
// сломает. Пустое имя — это null, а не пустая строка: у «нет имени» и
// «имя из пробелов» один смысл, и хранить их по-разному незачем.
export const trimName = raw =>
  (typeof raw === 'string' ? raw : '').replace(/\s+/g, ' ').trim().slice(0, MAX_NAME) || null;
