// Кто сейчас главный на экране.
//
// Закрепляет человек, но одно решение приложение принимает само: когда
// собеседник начинает показывать экран, показ затевают ровно ради того,
// чтобы на него смотрели. Догадаться про кнопку закрепления в этот момент
// — лишнее требование к человеку.
//
// Два правила ограничивают эту самодеятельность:
// — занятое место не отбираем. Если человек уже выбрал, на кого смотреть,
//   его выбор старше нашей догадки;
// — свой экран сам не закрепляем. Показывающий и так видит то, что
//   показывает, а закрепив, он потерял бы из виду собеседников. Но если он
//   закрепил свой экран руками — это его право, и отбирать нельзя.

const SCREEN = '|screen';
const SELF = 'self' + SCREEN;

const peerScreens = peers =>
  new Set((peers ?? []).filter(peer => peer.screen).map(peer => peer.peerId + SCREEN));

// Возвращает новое закрепление и новый набор виденных показов. Чистая
// функция: ничего не помнит сама, всё приходит доводами.
export const followScreens = ({peers, selfScreen = null, pinned = null, seen = new Set()}) => {
  const now = peerScreens(peers);
  const появился = [...now].find(id => !seen.has(id));
  if (появился && !pinned) return {pinned: появился, seen: now};

  // Показ кончился, а крупным был он — возвращаем обычную раскладку, иначе
  // экран остался бы пустым. Свой показ живёт отдельной приметой: в набор
  // чужих он не попадает, и без этой проверки закреплённый свой экран
  // отцеплялся бы сам собой на первой же перерисовке.
  const живо = pinned === SELF ? Boolean(selfScreen) : now.has(pinned);
  if (pinned?.endsWith(SCREEN) && !живо) return {pinned: null, seen: now};

  return {pinned, seen: now};
};
