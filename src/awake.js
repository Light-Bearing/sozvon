// Экран телефона гаснет — и разговор обрывается.
//
// Виноват не наш код, а то, что делает с невидимой страницей телефон:
// сперва он приостанавливает AudioContext и отбирает камеру, а немного
// погодя может заморозить страницу целиком вместе с соединением. Никакого
// события «меня заморозили» при этом не приходит — со стороны собеседника
// человек просто замолкает.
//
// Отсюда два средства, и оба нужны.
//
// Первое — просить экран не гаснуть, пока идёт разговор. Так делают все
// звонилки, и это единственный способ вовсе не доводить до заморозки.
// Работает не везде: блокировку дают не все браузеры и не всегда, а
// человек волен нажать кнопку выключения сам.
//
// Второе — возвращать отобранное, как только страница снова видна. Оно
// же и страховка на случай, когда первое не сработало.

export const createAwake = ({onWake} = {}) => {
  let lock = null;
  let wanted = false;

  const hold = async () => {
    // Блокировку дают только видимой странице: просить её из скрытой —
    // верный отказ, и просить незачем.
    if (!wanted || lock || document.visibilityState !== 'visible') return;
    try {
      lock = (await navigator.wakeLock?.request('screen')) ?? null;
      // Телефон снимает блокировку сам, как только страница скрылась.
      // Без этого мы бы считали её действующей и не попросили заново.
      lock?.addEventListener?.('release', () => {
        lock = null;
      });
    } catch {
      // Не дали — не беда: экран погаснет как обычно, а всё, что телефон
      // отберёт, вернёт onWake при возвращении. Разговор от отказа в
      // блокировке падать не должен.
      lock = null;
    }
  };

  const onVisibility = () => {
    if (document.visibilityState !== 'visible') return;
    void hold();
    onWake?.();
  };

  return {
    start: async () => {
      if (wanted) return;
      wanted = true;
      document.addEventListener('visibilitychange', onVisibility);
      await hold();
    },

    stop: async () => {
      wanted = false;
      document.removeEventListener('visibilitychange', onVisibility);
      const held = lock;
      lock = null;
      // release() может отказать, если блокировку уже сняли за нас, —
      // отказ здесь ничего не значит.
      await held?.release?.().catch?.(() => {});
    },

    // Только для проверок: держим ли блокировку прямо сейчас.
    held: () => Boolean(lock),
  };
};
