// Библиотека рассказывает о неудачах свободными строками по-английски.
// Здесь они превращаются в несколько опознанных видов беды — чтобы экран
// мог сказать человеку правду вместо вечного «жду, когда зайдут».
//
// Разбор по строкам хрупок: обновится библиотека — поменяются и тексты.
// Поэтому неузнанное честно зовётся 'unknown' и никогда не выдаёт себя за
// узнанное, а тесты держат список ровно тех строк, что библиотека отдаёт
// сейчас (см. tests/trouble.test.js).

// Собеседник найден через канал, описания соединения разошлись по адресам,
// а прямой путь между устройствами так и не сложился. Почти всегда — сеть:
// один из участников за таким NAT, сквозь который без ретранслятора не
// пройти.
const NO_PATH = 'no-path';
// В комнате с тем же именем сидит кто-то с другим ключом. При нашем способе
// выводить и имя, и ключ из одного секрета это значит только одно: ссылка
// у собеседника не та.
const WRONG_KEY = 'wrong-key';
// Соединение поднялось, но разговор о нём не довели до конца.
const HANDSHAKE = 'handshake';
const UNKNOWN = 'unknown';

export const TROUBLES = {NO_PATH, WRONG_KEY, HANDSHAKE, UNKNOWN};

const RULES = [
  [/after exchanging SDP/i, NO_PATH],
  [/incorrect (room )?password/i, WRONG_KEY],
  [/handshake/i, HANDSHAKE],
];

export const troubleFrom = error => {
  const text = typeof error === 'string' ? error : (error?.message ?? '');
  return RULES.find(([pattern]) => pattern.test(text))?.[1] ?? UNKNOWN;
};
