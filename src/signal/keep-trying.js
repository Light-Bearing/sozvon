// Каналы сигнализации не должны сдаваться.
//
// Библиотека переподключает закрывшийся канал с удвоением паузы — 3, 7, 13,
// 27, 53 секунды — и, дойдя до минуты, бросает его НАСОВСЕМ, до
// перезагрузки страницы. Сеть пропала на минуту (лифт, метро, перезапуск
// роутера) — и после её возвращения собеседники друг друга уже не находят:
// каналы мертвы, хотя сеть давно есть. Защита по событиям «сеть пропала /
// появилась» у библиотеки есть, но при смене Wi-Fi на мобильный интернет
// эти события часто не приходят.
//
// У библиотеки есть пара «приостановить / возобновить переподключение»:
// пока приостановлено, закрывшийся канал ждёт, не наращивая паузу и не
// сдаваясь. Сторож держит переподключение приостановленным и раз в every
// мс отпускает — выходит ровный повтор раз в несколько секунд, сколько
// угодно долго.
//
// Тонкость: после «возобновить» библиотека снимает свою блокировку не сразу,
// а следующим микрошагом, и только потом запускает ждавшие каналы. Снова
// приостанавливаем тоже микрошагом — ровно между этими двумя событиями,
// иначе «приостановить» попало бы в ещё не снятую блокировку и ничего бы
// не сделало.

const EVERY_MS = 4000;

export const keepRelaysTrying = ({pause, resume, every = EVERY_MS} = {}) => {
  pause();
  const timer = setInterval(() => {
    resume();
    queueMicrotask(pause);
  }, every);
  return () => {
    clearInterval(timer);
    resume();
  };
};
