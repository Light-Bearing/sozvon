// Сколько столбцов выбрать под плитки.
//
// Раньше столбцы раскладывал сам CSS: `repeat(auto-fit, minmax(18rem, 1fr))`.
// Он честно набивает ряд до отказа и переносит остаток — и именно поэтому
// раскладка выходила неудачной. Четверо на ноутбуке вставали в один ряд
// четырьмя узкими башнями вместо квадрата два на два; пятый человек
// оказывался один в ряду, а три клетки рядом пустовали.
//
// Правильный ответ зависит не от ширины клетки, а от пропорций: надо
// перебрать все раскладки и взять ту, где плитка выходит крупнее всего.
// Перебор короткий — столбцов не больше, чем людей.

// Камеры снимают широко: и 1280×720, и 640×360 из нашей лестницы — 16:9.
// Клетка, далёкая от этих пропорций, режет кадр по краям.
export const CAMERA_RATIO = 16 / 9;

export const bestColumns = ({count, width, height, gap = 8, ratio = CAMERA_RATIO}) => {
  if (!(count > 1) || !(width > 0) || !(height > 0)) return 1;

  let best = 1;
  let bestArea = -1;

  for (let columns = 1; columns <= count; columns++) {
    const rows = Math.ceil(count / columns);
    const cellW = (width - gap * (columns - 1)) / columns;
    const cellH = (height - gap * (rows - 1)) / rows;
    if (cellW <= 0 || cellH <= 0) continue;

    // Сколько кадра поместится в клетку, не потеряв пропорций: упираемся
    // либо в ширину, либо в высоту.
    const shownW = Math.min(cellW, cellH * ratio);
    const area = shownW * (shownW / ratio);

    // Строго больше: при равной площади выигрывает меньшее число столбцов,
    // то есть раскладка поспокойнее. Двое на широком экране встанут рядом,
    // а не один под другим, потому что рядом им просто просторнее.
    if (area > bestArea) {
      bestArea = area;
      best = columns;
    }
  }

  return best;
};

// Неполный последний ряд ставим по центру. Иначе одинокая плитка жмётся к
// левому краю, а рядом зияют пустые клетки, и раскладка выглядит не
// продуманной, а сломанной.
//
// Считаем в ПОЛУКЛЕТКАХ: столбцов вдвое больше, каждая плитка занимает два.
// Целыми клетками двойку в трёх столбцах не выровнять — отступ выходит
// половинным, и остаётся выбирать между «прижать влево» и «прижать
// вправо». С полуклетками центр находится всегда.
export const HALVES = 2;

export const lastRowOffset = ({count, columns}) => {
  const tail = count % columns;
  return tail === 0 ? 0 : columns - tail;
};
